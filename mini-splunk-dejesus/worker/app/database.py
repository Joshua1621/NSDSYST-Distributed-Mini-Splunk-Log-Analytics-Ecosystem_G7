"""
MongoDB repository used by the Worker.
"""

from __future__ import annotations

from datetime import datetime

from pymongo import MongoClient
from pymongo.collection import Collection

from shared.config import settings
from shared.logging import get_logger

logger = get_logger("worker.database")


class MongoRepository:
    """
    MongoDB repository responsible for storing parsed logs.

    Uses idempotent upserts based on the deterministic
    message_id generated by the parser.
    """

    def __init__(self) -> None:

        logger.info("Connecting to MongoDB...")

        self.client = MongoClient(
            settings.mongo_uri,
            serverSelectionTimeoutMS=3000,
        )

        self.database = self.client[settings.database]

        self.collection: Collection = (
            self.database[settings.collection]
        )

        self.lock_collection: Collection = (
            self.database[settings.lock_collection]
        )

        logger.info("MongoDB connection established.")

    ########################################################
    # Log Storage
    ########################################################

    def upsert_log(
        self,
        log: dict,
    ) -> None:
        """
        Insert or update a parsed log entry.

        The deterministic message_id guarantees
        idempotent writes during message redelivery.
        """

        self.collection.update_one(
            {
                "message_id": log["message_id"],
            },
            {
                "$set": log,
            },
            upsert=True,
        )

    ########################################################
    # Distributed Lock
    ########################################################

    def purge_lock_active(self) -> bool:
        """
        Returns True when a valid purge lock exists.

        The Worker only checks the lock state.
        Lock acquisition and release are handled
        exclusively by the Gateway.
        """

        now = datetime.utcnow()

        return (
            self.lock_collection.count_documents(
                {
                    "_id": "purge_lock",
                    "expires_at": {
                        "$gt": now,
                    },
                }
            )
            > 0
        )

    ########################################################
    # Cleanup
    ########################################################

    def close(self) -> None:
        """
        Close MongoDB connection.
        """

        self.client.close()

        logger.info("MongoDB connection closed.")